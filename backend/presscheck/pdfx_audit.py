"""Independent qpdf-backed audit of Magdobe's deliberately narrow PDF subset.

This is not an ISO PDF/X certification engine. It checks the bytes generated by
a separate writer and rejects content outside the subset we can inspect.
"""
from datetime import datetime, timedelta, timezone
import hashlib
import math
import re
import zlib

from defusedxml import ElementTree as SafeET

MAX_DECODED_STREAM = 64 * 1024 * 1024
MAX_TOTAL_DECODED = 128 * 1024 * 1024
MAX_OBJECTS = 250_000
MAX_OPERATORS = 4_000_000
MAX_CONTENT_TOKENS = 2_000_000
POINTS_PER_MM = 72 / 25.4


def _decoded(stream, limit=MAX_DECODED_STREAM):
    """Bound supported decompression before qpdf parses a content stream."""
    raw = stream.read_raw_bytes()
    if len(raw) > limit:
        raise ValueError("PDF stream exceeds the inspection limit")
    filters = stream.get("/Filter")
    if filters is None:
        return raw
    from pikepdf import Array
    values = [str(v) for v in filters] if isinstance(filters, Array) else [str(filters)]
    if values != ["/FlateDecode"] or stream.get("/DecodeParms") is not None:
        raise ValueError("PDF stream uses an unsupported filter or predictor")
    decoder = zlib.decompressobj()
    data = decoder.decompress(raw, limit+1)
    if len(data) > limit or decoder.unconsumed_tail or decoder.unused_data or not decoder.eof:
        raise ValueError("Decoded PDF stream exceeds the limit or is incomplete")
    return data


def _finite(value):
    number = float(value)
    if not math.isfinite(number):
        raise ValueError("Nonfinite PDF number")
    return number


def _pdf_date(value):
    match = re.fullmatch(r"D:(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})(Z|[+-]\d{2}'?\d{2}'?)?", str(value))
    if not match:
        raise ValueError("Missing or unsupported PDF date")
    zone = match[7]
    tz = None
    if zone == "Z":
        tz = timezone.utc
    elif zone:
        compact = zone.replace("'", "")
        hours, minutes = int(compact[1:3]), int(compact[3:5])
        if hours > 23 or minutes > 59:
            raise ValueError("Invalid PDF date timezone")
        tz = timezone((1 if compact[0] == "+" else -1)*timedelta(hours=hours, minutes=minutes))
    return datetime(*(int(v) for v in match.groups()[:6]), tzinfo=tz)


def audit_pdf(path, job, expected_icc=None, *, source=False):
    import pikepdf

    findings, seen, active_forms, allowed_streams = [], set(), set(), set()
    metrics = {"vector_paths": 0, "text_objects": 0, "raster_objects": 0,
               "alpha_states": 0, "transparency_groups": 0, "color_spaces": [],
               "pages": 0, "pdf_version": None, "pdfx_claim": None,
               "auditor": "pikepdf/qpdf supported-subset audit",
               "pikepdf_version": pikepdf.__version__, "qpdf_version": pikepdf.__libqpdf_version__}
    prefix = "pdf.source." if source else "pdf.output."
    recorded = set()
    operator_count = 0
    object_count = 0
    token_count = 0
    spaces = set()

    def add(rule, status, message, **details):
        key = (rule, status, message)
        if key in recorded:
            return
        recorded.add(key)
        findings.append({"id": f"F{len(findings)+1:04}", "rule_id": prefix+rule,
                         "status": status, "message": message, "object_ids": [], **details})

    def identity(obj):
        return tuple(obj.objgen) if getattr(obj, "is_indirect", False) else ("direct", id(obj))

    def color_space(value, resources, chain=0):
        if chain > 12:
            raise ValueError("Cyclic or excessive color-space references")
        name = str(value)
        simple = {"/DeviceGray": "Gray", "/G": "Gray", "/DeviceRGB": "RGB", "/RGB": "RGB", "/DeviceCMYK": "CMYK", "/CMYK": "CMYK"}
        if name in simple:
            result = simple[name]
        elif isinstance(value, pikepdf.Array):
            kind = str(value[0]) if value else ""
            if kind == "/ICCBased" and len(value) == 2 and isinstance(value[1], pikepdf.Stream):
                profile = value[1]
                allowed_streams.add(identity(profile))
                data = _decoded(profile, 16*1024*1024)
                channels = int(profile.get("/N", 0))
                result = {1: "Gray", 3: "RGB", 4: "CMYK"}.get(channels)
                signature = {1: b"GRAY", 3: b"RGB ", 4: b"CMYK"}.get(channels)
                if not result or len(data) < 128 or data[36:40] != b"acsp" or data[16:20] != signature:
                    raise ValueError("Invalid ICC-based PDF color space")
                alternate = profile.get("/Alternate")
                if alternate is not None and color_space(alternate, resources, chain+1) != result:
                    raise ValueError("ICC alternate color space is inconsistent")
            elif kind in ("/CalGray", "/CalRGB") and len(value) == 2:
                result = "Gray" if kind == "/CalGray" else "RGB"
            else:
                raise ValueError("Spot, DeviceN, indexed, pattern or unrecognized color space is outside this export subset")
        else:
            aliases = resources.get("/ColorSpace", {})
            if name not in aliases:
                raise ValueError("Unresolved PDF color-space resource")
            return color_space(aliases[name], resources, chain+1)
        spaces.add(result)
        allowed = {"RGB", "Gray"} if source else {"CMYK", "Gray"}
        if result not in allowed:
            raise ValueError("RGB draft contains preconverted CMYK" if source else "RGB remains in output paint or a transparency blend space")
        return result

    def resources_check(resources):
        if resources.get("/Font"):
            raise ValueError("Font resources remain; the supported export requires text outlines")
        if resources.get("/Pattern") or resources.get("/Shading"):
            raise ValueError("Patterns and shadings require a separate audited export mode")
        for value in resources.get("/ColorSpace", {}).values():
            color_space(value, resources)

    def group_check(group, resources):
        if group is None:
            return
        if str(group.get("/S")) != "/Transparency":
            raise ValueError("Unsupported PDF group")
        metrics["transparency_groups"] += 1
        if group.get("/CS") is not None:
            color_space(group["/CS"], resources)

    def graphics_state(state, resources, depth):
        for name in ("/ca", "/CA"):
            if name in state:
                alpha = _finite(state[name])
                if not 0 <= alpha <= 1:
                    raise ValueError("Invalid transparency alpha")
                metrics["alpha_states"] += alpha < 1
        if str(state.get("/BM", "/Normal")) not in ("/Normal", "/Compatible"):
            raise ValueError("Non-normal blend mode requires separate validation")
        if state.get("/SMask") is not None and str(state["/SMask"]) != "/None":
            raise ValueError("Soft masks are outside the supported solid-vector export subset")
        if bool(state.get("/OP", False)) or bool(state.get("/op", False)):
            raise ValueError("Overprinting is outside the selected ICC-only export policy")
        if any(key in state for key in ("/TR", "/TR2", "/HT", "/BG", "/UCR")):
            raise ValueError("Custom transfer, screening or black-generation state is unsupported")

    def content_check(stream, resources, depth=0):
        nonlocal operator_count, token_count
        if depth > 40:
            raise ValueError("Excessive Form XObject nesting")
        streams = list(stream) if isinstance(stream, pikepdf.Array) else [stream]
        for part in streams:
            if not isinstance(part, pikepdf.Stream):
                raise ValueError("Invalid page content stream")
            allowed_streams.add(identity(part))
            data = _decoded(part)
            # Native and pdfwrite solid-vector operands do not need strings,
            # dictionaries or nested arrays. Screen before qpdf builds a list
            # of every instruction/operand in this stream.
            lexical = re.sub(rb"%[^\r\n]*", b"", data)
            if re.search(rb"[(){}<>]", lexical):
                raise ValueError("Text strings or compound content operands are outside the solid-vector subset")
            array_depth = 0
            for token in re.finditer(rb"\[|\]|[^\x00\t\n\f\r \[\]]+", lexical):
                token_count += 1
                if token_count > MAX_CONTENT_TOKENS:
                    raise ValueError("PDF exceeds the content-token inspection limit")
                if token[0] == b"[":
                    array_depth += 1
                    if array_depth > 1:
                        raise ValueError("Nested content arrays are unsupported")
                elif token[0] == b"]":
                    array_depth -= 1
                    if array_depth < 0:
                        raise ValueError("Unbalanced content array")
            if array_depth:
                raise ValueError("Unbalanced content array")
        resources_check(resources)
        path_pending = False
        fill, stroke, stack = "Gray", "Gray", []
        passive = {"cm", "w", "J", "j", "M", "d", "ri", "W", "W*", "h"}
        path_ops = {"m", "l", "c", "v", "y", "re"}
        paint_ops = {"f", "F", "f*", "S", "s", "B", "B*", "b", "b*"}
        instructions = (instruction for part in streams for instruction in pikepdf.parse_content_stream(part))
        for instruction in instructions:
            if not hasattr(instruction, "operator"):
                metrics["raster_objects"] += 1
                raise ValueError("Inline raster images are forbidden in the vector export subset")
            operands, op = instruction.operands, str(instruction.operator)
            operator_count += 1
            if operator_count > MAX_OPERATORS:
                raise ValueError("PDF exceeds the content-operation limit")
            if op == "q":
                if operands: raise ValueError("Invalid graphics-state operands")
                stack.append((fill, stroke))
            elif op == "Q":
                if operands: raise ValueError("Invalid graphics-state operands")
                if not stack:
                    raise ValueError("Unbalanced PDF graphics-state stack")
                fill, stroke = stack.pop()
            elif op in path_ops:
                if len(operands) != {"m": 2, "l": 2, "c": 6, "v": 4, "y": 4, "re": 4}[op]:
                    raise ValueError("Invalid PDF path operands")
                for number in operands:
                    _finite(number)
                path_pending = True
            elif op in paint_ops:
                if operands: raise ValueError("Invalid paint operands")
                if path_pending:
                    if op not in ("S", "s"):
                        spaces.add(fill)
                    if op in ("S", "s", "B", "B*", "b", "b*"):
                        spaces.add(stroke)
                    metrics["vector_paths"] += 1
                path_pending = False
            elif op == "n":
                if operands: raise ValueError("Invalid path operands")
                path_pending = False
            elif op in ("rg", "RG", "k", "K", "g", "G"):
                kind = "RGB" if op.lower() == "rg" else "CMYK" if op.lower() == "k" else "Gray"
                if len(operands) != {"RGB": 3, "CMYK": 4, "Gray": 1}[kind] or any(not 0 <= _finite(v) <= 1 for v in operands):
                    raise ValueError("Invalid PDF paint operands")
                color_space({"RGB": "/DeviceRGB", "CMYK": "/DeviceCMYK", "Gray": "/DeviceGray"}[kind], resources)
                if op.islower(): fill = kind
                else: stroke = kind
            elif op in ("cs", "CS"):
                if len(operands) != 1:
                    raise ValueError("Invalid color-space operator")
                kind = color_space(operands[0], resources)
                if op == "cs": fill = kind
                else: stroke = kind
            elif op in ("sc", "SC", "scn", "SCN"):
                kind = fill if op.islower() else stroke
                if len(operands) != {"RGB": 3, "CMYK": 4, "Gray": 1}[kind] or any(not 0 <= _finite(v) <= 1 for v in operands):
                    raise ValueError("Invalid or patterned color operands")
            elif op == "gs":
                if len(operands) != 1 or str(operands[0]) not in resources.get("/ExtGState", {}):
                    raise ValueError("Unresolved graphics-state resource")
                graphics_state(resources["/ExtGState"][str(operands[0])], resources, depth)
            elif op == "Do":
                if len(operands) != 1 or str(operands[0]) not in resources.get("/XObject", {}):
                    raise ValueError("Unresolved XObject resource")
                form = resources["/XObject"][str(operands[0])]
                if str(form.get("/Subtype")) == "/Image":
                    metrics["raster_objects"] += 1
                    raise ValueError("Raster artwork or rasterized vector content is forbidden")
                if str(form.get("/Subtype")) != "/Form":
                    raise ValueError("Unsupported XObject subtype")
                key = identity(form)
                if key in active_forms:
                    raise ValueError("Cyclic Form XObject reference")
                active_forms.add(key)
                for name, count in (("/Matrix", 6), ("/BBox", 4)):
                    value = form.get(name)
                    if value is not None and (len(value) != count or any(not math.isfinite(_finite(v)) for v in value)):
                        raise ValueError("Invalid Form XObject geometry")
                child_resources = form.get("/Resources", resources)
                group_check(form.get("/Group"), child_resources)
                content_check(form, child_resources, depth+1)
                active_forms.remove(key)
            elif op in ("BT", "ET", "Tf", "Tj", "TJ", "'", '"'):
                metrics["text_objects"] += 1
                raise ValueError("Editable text remains; export a copy with all glyphs outlined")
            elif op in passive:
                if op in ("W", "W*", "h"):
                    if operands: raise ValueError("Invalid path operands")
                elif op == "ri":
                    if len(operands) != 1 or str(operands[0]) not in ("/Perceptual", "/RelativeColorimetric", "/Saturation", "/AbsoluteColorimetric"):
                        raise ValueError("Invalid rendering intent")
                elif op == "d":
                    if len(operands) != 2 or not isinstance(operands[0], pikepdf.Array) or _finite(operands[1]) < 0:
                        raise ValueError("Invalid dash operands")
                    dashes = [_finite(v) for v in operands[0]]
                    if any(v < 0 for v in dashes) or (dashes and not any(dashes)):
                        raise ValueError("Invalid dash pattern")
                else:
                    if len(operands) != (6 if op == "cm" else 1):
                        raise ValueError("Invalid graphics-state operands")
                    values = [_finite(v) for v in operands]
                    if op in ("J", "j") and values[0] not in (0, 1, 2):
                        raise ValueError("Invalid line cap/join")
                    if op == "w" and values[0] < 0 or op == "M" and values[0] < 1:
                        raise ValueError("Invalid stroke width/miter limit")
            else:
                raise ValueError("Unsupported PDF content operator: " + op)
        if stack:
            raise ValueError("Unbalanced PDF graphics-state stack")

    try:
        with pikepdf.open(path, attempt_recovery=False, suppress_warnings=True) as pdf:
            metrics["pdf_version"] = str(pdf.pdf_version)
            if pdf.is_encrypted:
                raise ValueError("Encrypted PDF files are unsupported")
            if len(pdf.objects) > MAX_OBJECTS:
                raise ValueError("PDF exceeds the object-count limit")
            total_decoded = 0
            for obj in pdf.objects:
                if isinstance(obj, pikepdf.Stream):
                    if str(obj.get("/Type", "")) in ("/ObjStm", "/XRef"):
                        raise ValueError("Compressed object/xref streams are outside the native-draft export subset")
                    total_decoded += len(_decoded(obj))
                    if total_decoded > MAX_TOTAL_DECODED:
                        raise ValueError("PDF exceeds the aggregate decoded-stream inspection limit")
            errors = pdf.check_pdf_syntax()
            if errors:
                raise ValueError("qpdf reported PDF syntax problems")
            metrics["pages"] = len(pdf.pages)
            if len(pdf.pages) != 1:
                raise ValueError("This production export requires exactly one artboard/page")
            width = (job["trim_width_mm"]+2*job["bleed_mm"])*POINTS_PER_MM
            height = (job["trim_height_mm"]+2*job["bleed_mm"])*POINTS_PER_MM
            bleed = job["bleed_mm"]*POINTS_PER_MM
            expected_boxes = {"/MediaBox": [0, 0, width, height], "/BleedBox": [0, 0, width, height],
                              "/TrimBox": [bleed, bleed, width-bleed, height-bleed]}
            for page in pdf.pages:
                if int(page.obj.get("/Rotate", 0)) != 0 or _finite(page.obj.get("/UserUnit", 1)) != 1:
                    raise ValueError("Rotated or custom-unit PDF pages are outside this export subset")
                for key, expected in expected_boxes.items():
                    actual = page.obj.get(key)
                    if actual is None or len(actual) != 4 or any(abs(_finite(a)-b) > .02 for a, b in zip(actual, expected)):
                        raise ValueError("PDF physical " + key + " does not match the printer job")
                if "/ArtBox" in page.obj:
                    raise ValueError("Use TrimBox without a conflicting ArtBox")
                crop = page.obj.get("/CropBox")
                if crop is not None and (len(crop) != 4 or any(abs(_finite(a)-b) > .02 for a, b in zip(crop, expected_boxes["/MediaBox"]))):
                    raise ValueError("CropBox unexpectedly clips production bleed")
                resources = page.obj.get("/Resources", {})
                group_check(page.obj.get("/Group"), resources)
                content_check(page.obj.get("/Contents"), resources)
            add("geometry", "pass", "Page, trim and bleed boxes match the physical job", measured=[width, height], unit="pt")
            add("vector_content", "pass", "Supported vector paths are present; no font or raster dependency was found", measured=metrics["vector_paths"])
            if metrics["vector_paths"] == 0:
                raise ValueError("No painted vector geometry was found")
            metadata = pdf.Root.get("/Metadata")
            if metadata is not None:
                allowed_streams.add(identity(metadata))
            if not source:
                intents = pdf.Root.get("/OutputIntents", [])
                if len(intents) != 1 or str(intents[0].get("/S")) != "/GTS_PDFX":
                    raise ValueError("Exactly one embedded production OutputIntent is required")
                intent = intents[0]
                profile = intent.get("/DestOutputProfile")
                if not isinstance(profile, pikepdf.Stream) or int(profile.get("/N", 0)) != 4:
                    raise ValueError("OutputIntent must embed the selected four-channel ICC profile")
                allowed_streams.add(identity(profile))
                embedded = _decoded(profile, 16*1024*1024)
                if expected_icc is None or embedded != expected_icc:
                    raise ValueError("Embedded OutputIntent ICC bytes differ from the selected profile")
                if len(embedded) < 132 or embedded[36:40] != b"acsp" or embedded[12:20] != b"prtrCMYK" or embedded[8] not in (2, 4):
                    raise ValueError("OutputIntent is not an ICC v2/v4 CMYK printer profile")
                metrics["icc_sha256"] = hashlib.sha256(embedded).hexdigest()
                settings = job["pdf"]
                if str(intent.get("/OutputConditionIdentifier", "")) != settings["output_condition_identifier"]:
                    raise ValueError("Output condition identifier differs from the selected printer job")
                for key, setting in (("/OutputCondition", "output_condition"), ("/RegistryName", "registry_name")):
                    if str(intent.get(key, "")) != settings[setting]:
                        raise ValueError("OutputIntent " + key + " differs from the printer job")
                add("output_intent", "pass", "Selected CMYK ICC profile is embedded byte-for-byte", measured=metrics["icc_sha256"])
                if settings["target"] == "pdfx4":
                    if pdf.pdf_version != "1.6":
                        raise ValueError("PDF/X-4 export must use the supported PDF 1.6 writer mode")
                    if str(pdf.docinfo.get("/GTS_PDFXVersion", "")) != "PDF/X-4" or str(pdf.docinfo.get("/Trapped", "")) != "/False":
                        raise ValueError("PDF/X identification or trapping declaration is missing/inconsistent")
                    info_dates = {key: _pdf_date(pdf.docinfo.get(key, "")) for key in ("/CreationDate", "/ModDate")}
                    if not pdf.docinfo.get("/Title") or len(pdf.trailer.get("/ID", [])) != 2:
                        raise ValueError("PDF/X title or document IDs are missing")
                    if not isinstance(metadata, pikepdf.Stream):
                        raise ValueError("PDF/X-4 XMP metadata is missing")
                    xml = SafeET.fromstring(_decoded(metadata, 1024*1024), forbid_dtd=True)
                    values = {}
                    for element in xml.iter():
                        values.update(element.attrib)
                        if element.text and element.text.strip():
                            values[element.tag] = element.text.strip()
                    key = "{http://www.npes.org/pdfx/ns/id/}GTS_PDFXVersion"
                    if values.get(key) != "PDF/X-4":
                        raise ValueError("XMP does not declare PDF/X-4")
                    if values.get("{http://ns.adobe.com/pdf/1.3/}Trapped") != "False":
                        raise ValueError("XMP trapping declaration differs from document information")
                    for name in ("CreateDate", "ModifyDate", "MetadataDate"):
                        value = values.get("{http://ns.adobe.com/xap/1.0/}"+name)
                        if not value:
                            raise ValueError("Required XMP date is absent")
                        parsed_date = datetime.fromisoformat(value.replace("Z", "+00:00"))
                        if parsed_date.tzinfo is None:
                            raise ValueError("XMP dates must specify a timezone")
                        info_key = {"CreateDate": "/CreationDate", "ModifyDate": "/ModDate"}.get(name)
                        if info_key and info_dates[info_key].tzinfo is not None and parsed_date != info_dates[info_key]:
                            raise ValueError("XMP and document dates are inconsistent")
                    title = xml.find(".//{http://purl.org/dc/elements/1.1/}title")
                    if title is None or not any((e.text or "").strip() == str(pdf.docinfo["/Title"]) for e in title.iter()):
                        raise ValueError("XMP document title is absent")
                    metrics["pdfx_claim"] = "PDF/X-4"
                    add("pdfx_metadata", "pass", "PDF 1.6, PDF/X-4 identification, XMP, dates, IDs and trapping declaration are present")
            forbidden_keys = {"/OpenAction", "/AA", "/A", "/AcroForm", "/EmbeddedFiles", "/AF", "/EF", "/Ref", "/JavaScript", "/JS", "/RichMediaContent", "/Collection", "/Alternates", "/OPI", "/Annots", "/OCProperties", "/Outlines", "/Threads"}
            forbidden_actions = {"/JavaScript", "/Launch", "/URI", "/GoToR", "/SubmitForm", "/ImportData"}
            def inspect_object(obj, depth=0):
                nonlocal object_count
                if depth > 100:
                    raise ValueError("Excessive PDF object nesting")
                if not isinstance(obj, (pikepdf.Dictionary, pikepdf.Stream, pikepdf.Array)):
                    return
                key = identity(obj)
                if getattr(obj, "is_indirect", False):
                    if key in seen:
                        return
                    seen.add(key)
                object_count += 1
                if object_count > MAX_OBJECTS:
                    raise ValueError("PDF exceeds the object inspection limit")
                if isinstance(obj, (pikepdf.Dictionary, pikepdf.Stream)):
                    if forbidden_keys & set(obj.keys()) or str(obj.get("/S", "")) in forbidden_actions or str(obj.get("/Type", "")) == "/Filespec":
                        raise ValueError("Interactive, external, attached or optional-content features are outside this export subset")
                    if isinstance(obj, pikepdf.Stream):
                        if "/F" in obj:
                            raise ValueError("External-file PDF streams are forbidden")
                        if identity(obj) not in allowed_streams and str(obj.get("/Type", "")) not in ("/XRef", "/ObjStm"):
                            raise ValueError("Unrecognized or unused PDF stream requires separate validation")
                    for value in obj.values():
                        inspect_object(value, depth+1)
                else:
                    for value in obj:
                        inspect_object(value, depth+1)
            for obj in pdf.objects:
                inspect_object(obj)
            if pdf.get_warnings():
                raise ValueError("qpdf issued warnings while inspecting the PDF")
            add("structure", "pass", "qpdf syntax checks passed without recovery, warnings, encryption or prohibited features")
            add("color", "pass", "Source RGB/gray color spaces are supported" if source else "Paint and declared blend spaces contain CMYK/gray only")
    except Exception as exc:
        add("supported_subset", "fail", str(exc)[:500])
    metrics["color_spaces"] = sorted(spaces)
    return {"status": "fail" if any(f["status"] == "fail" for f in findings) else "pass_supported_checks",
            "findings": findings, "metrics": metrics}
